function guide({ id, title, subtitle, author, era, category, tags, intro, order, cover, chapters }) {
  const book = importers.buildBook({
    id,
    title,
    subtitle,
    author,
    era,
    category,
    tags,
    intro,
    script: 'simplified',
    chapters,
    source: {
      provider: '万卷阁原创导读',
      license: '本程序原创整理，采用 MIT 许可；引用古籍原文属公有领域',
      note: '为导读/考据文字，不是古籍全文的伪造版本'
    },
    builtin: true,
    cover,
    order
  });
  save(book);
  return book;
}

