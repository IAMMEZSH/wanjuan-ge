/**
 * 咒文的原文多为短句，逐句分段在阅读器里会显得零碎。
 * 此处把同属一段落群的短句并合，使每段落在 80—220 字之间；
 * 只做并合，不改动任何字句。
 */
function splitMarkers(paragraphs, min = 80) {
  const out = [];
  for (const paragraph of paragraphs) {
    let rest = paragraph;
    let at = rest.indexOf('【', 1);
    while (at > -1) {
      const head = rest.slice(0, at);
      const tail = rest.slice(at);
      const boundary = /[。」』）]$/.test(head);
      if (boundary && head.length >= min && tail.length >= min) {
        out.push(head);
        rest = tail;
        at = rest.indexOf('【', 1);
      } else {
        at = rest.indexOf('【', at + 1);
      }
    }
    out.push(rest);
  }
  return out;
}

function packParagraphs(paragraphs, min = 80, max = 220) {
  const packed = [];
  let buffer = '';
  const isMarker = (text) => /^(【|不同纸草此句有异)/.test(text);
  for (const raw of paragraphs) {
    const text = String(raw || '').trim();
    if (!text) continue;
    if (!buffer) {
      buffer = text;
      continue;
    }
    if (buffer.length >= min) {
      packed.push(buffer);
      buffer = text;
      continue;
    }
    if (isMarker(text)) {
      const last = packed[packed.length - 1];
      if (last && last.length + buffer.length <= max) {
        packed[packed.length - 1] = last + buffer;
        buffer = text;
        continue;
      }
    }
    if (buffer.length + text.length <= max) {
      buffer += text;
      continue;
    }
    packed.push(buffer);
    buffer = text;
  }
  if (buffer) {
    const last = packed[packed.length - 1];
    if (buffer.length < min && last && last.length + buffer.length <= max) {
      packed[packed.length - 1] = last + buffer;
    } else {
      packed.push(buffer);
    }
  }
  return packed;
}

