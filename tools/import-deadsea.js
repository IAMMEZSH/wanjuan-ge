function loadChapters(file) {
  const full = path.join(SRC, file);
  if (!fs.existsSync(full)) throw new Error(`缺少译稿：${file}`);
  const data = JSON.parse(fs.readFileSync(full, 'utf8'));
  if (!data || !Array.isArray(data.chapters) || !data.chapters.length) {
    throw new Error(`译稿为空：${file}`);
  }
  return data.chapters
    .map((chapter) => ({
      title: String(chapter.title || '').trim(),
      paragraphs: (chapter.paragraphs || []).map((p) => String(p).trim()).filter(Boolean)
    }))
    .filter((chapter) => chapter.title && chapter.paragraphs.length);
}

